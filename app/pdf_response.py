from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer

from app.config import ROOT_DIR

MESSAGE_DIR = ROOT_DIR / "message_to_user"


def _safe_filename(text: str, max_len: int = 40) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9_-]+", "_", (text or "resolution").strip())
    cleaned = cleaned.strip("_") or "resolution"
    return cleaned[:max_len]


def save_final_resolution_pdf(
    *,
    final_resolution: str,
    user_query: str = "",
    session_id: str = "",
    intent: str = "",
    approved: bool | None = None,
    needs_approval: bool = False,
) -> Path:
    """Write the agent final resolution to message_to_user/*.pdf and return the path."""
    MESSAGE_DIR.mkdir(parents=True, exist_ok=True)

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    sid = (session_id or "session")[:8]
    path = MESSAGE_DIR / f"final_resolution_{stamp}_{sid}.pdf"

    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "TitleCustom",
        parent=styles["Heading1"],
        fontSize=16,
        textColor=HexColor("#0f172a"),
        spaceAfter=6,
    )
    label = ParagraphStyle(
        "Label",
        parent=styles["Normal"],
        fontSize=10,
        textColor=HexColor("#5c6570"),
        spaceBefore=10,
        spaceAfter=4,
    )
    body = ParagraphStyle(
        "BodyCustom",
        parent=styles["Normal"],
        fontSize=11,
        textColor=HexColor("#1a1d23"),
        leading=16,
        spaceAfter=8,
    )
    meta = ParagraphStyle(
        "Meta",
        parent=styles["Normal"],
        fontSize=9,
        textColor=HexColor("#64748b"),
        spaceBefore=14,
    )

    hitl_status = "n/a"
    if needs_approval:
        if approved is True:
            hitl_status = "approved"
        elif approved is False:
            hitl_status = "rejected"
        else:
            hitl_status = "pending"

    resolution_html = escape(final_resolution or "(empty)").replace("\n", "<br/>")
    query_html = escape(user_query or "(n/a)")

    doc = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=0.9 * inch,
        rightMargin=0.9 * inch,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
    )
    story = [
        Paragraph("IT Helpdesk — Final Resolution", title),
        Paragraph("User-facing response generated by the multi-agent system.", body),
        HRFlowable(width="100%", thickness=1, color=HexColor("#0b6e4f"), spaceAfter=10),
        Paragraph("USER QUERY", label),
        Paragraph(query_html, body),
        Paragraph("FINAL RESOLUTION", label),
        Paragraph(resolution_html, body),
        Spacer(1, 8),
        Paragraph(
            f"Session: {escape(session_id or 'n/a')} &nbsp;|&nbsp; "
            f"Intent: {escape(intent or 'n/a')} &nbsp;|&nbsp; "
            f"HITL: {escape(hitl_status)} &nbsp;|&nbsp; "
            f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            meta,
        ),
    ]
    doc.build(story)
    return path
